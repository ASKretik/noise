// bench3d/priors3d.js -- regenerate sim3d/dispatch/priors3d.js. `npm run priors3d`
//
// The habit file scores a player against a population. That population is the 2D game's
// five bots (drunk, beeline, wallHugger, coverCrawler, evader) playing city districts on
// the `next` rules with no habit tactics: the mean and spread of each habit across their
// runs. The five habit bots (bots3d.js) are left out on purpose -- they are what the file
// has to tell apart from ordinary play, not part of ordinary play.
//
// Like the 2D priors, a build artefact: regenerate after a change to how habits are
// measured or to anything that changes how bots play a city, and not otherwise.

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DistrictRunner } from '../web3d/runner.js';
import { HabitFile, HABIT_KEYS } from '../sim3d/dispatch/habits.js';
import { drive, POPULATION } from './bots3d.js';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
export const PRIOR_DISTRICTS = [5, 15, 30, 50, 70, 90];
export const PRIOR_SEEDS = 4;
/** No habit may have a spread under this: a near-constant habit would make z explode. */
export const STD_FLOOR = 0.05;

export function measurePopulation({ districts = PRIOR_DISTRICTS, seeds = PRIOR_SEEDS, bots = POPULATION } = {}) {
  const samples = Object.fromEntries(HABIT_KEYS.map((k) => [k, []]));
  let runs = 0;
  for (const bot of bots) {
    for (const d of districts) {
      for (let k = 0; k < seeds; k++) {
        const r = new DistrictRunner({ profileId: `prior-${bot}-${k}`, district: d, tier: 'medium', habits: new HabitFile() });
        const { habits } = drive(r, bot, 1000 + d * 7 + k, 900);
        runs++;
        for (const h of HABIT_KEYS) if (Number.isFinite(habits?.[h])) samples[h].push(habits[h]);
      }
    }
  }
  const priors = {};
  for (const h of HABIT_KEYS) {
    const v = samples[h];
    const mean = v.length ? v.reduce((a, b) => a + b, 0) / v.length : 0;
    const sd = v.length > 1 ? Math.sqrt(v.reduce((a, b) => a + (b - mean) ** 2, 0) / (v.length - 1)) : STD_FLOOR;
    priors[h] = { mean: +mean.toFixed(4), std: +Math.max(STD_FLOOR, sd).toFixed(4), n: v.length };
  }
  return { priors, runs };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const t0 = Date.now();
  const { priors, runs } = measurePopulation();
  const lines = HABIT_KEYS.map((h) => `  ${h}: { mean: ${priors[h].mean}, std: ${priors[h].std} },   // ${priors[h].n} runs with evidence`);
  writeFileSync(resolve(ROOT, 'sim3d/dispatch/priors3d.js'), `// sim3d/dispatch/priors3d.js -- GENERATED by \`npm run priors3d\`. Do not edit by hand.
//
// Each habit's mean and spread across the 2D game's five bots playing city districts
// ${PRIOR_DISTRICTS.join(', ')} on the \`next\` rules, ${PRIOR_SEEDS} seeds each, MEDIUM, no habit
// tactics (${runs} runs). See bench3d/priors3d.js.
export const HABIT_PRIORS = Object.freeze({
${lines.join('\n')}
});
export const PRIORS_META = Object.freeze({ runs: ${runs}, districts: [${PRIOR_DISTRICTS.join(', ')}], seeds: ${PRIOR_SEEDS} });
`);
  console.log(`priors3d: ${runs} runs in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  for (const h of HABIT_KEYS) console.log(`  ${h.padEnd(7)} mean ${priors[h].mean}  std ${priors[h].std}  (${priors[h].n} runs)`);
}
