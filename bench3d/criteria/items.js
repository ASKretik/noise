// bench3d/criteria/items.js -- 3D-14: fewer bolts deeper into each belt (spec-3d-next.md N1).

import { generateLevel } from '../../sim/gen.js';
import { levelParams } from '../../sim/difficulty.js';
import { FieldPool, bfsField, UNREACHABLE } from '../../sim/pathfind.js';
import { boltKeepCount, thinBolts, beltDepth } from '../../sim3d/bolts.js';
import { DistrictRunner } from '../../web3d/runner.js';

const pool = new FieldPool(32 * 20);

export const criteria = [{
  n: 14,
  text: 'Bolt thinning: every district 1-100 keeps max(1, round(n(1 - 2k/27))) of its generated bolts, a reachable subset, the same one every time, and the runner applies it',
  async fn() {
    const problems = [];
    const byDepth = Array.from({ length: 10 }, () => ({ gen: 0, kept: 0, n: 0 }));
    for (const profile of ['main', 'guest', 'bench']) {
      for (let d = 1; d <= 100; d++) {
        const lv = generateLevel(profile, d, { pool, params: levelParams(d, 'medium') });
        const kept = thinBolts(lv.bolts, d, profile);
        const again = thinBolts(lv.bolts, d, profile);
        const want = boltKeepCount(lv.bolts.length, d);
        if (kept.length !== want) problems.push(`${profile} D${d}: kept ${kept.length}, want ${want}`);
        const key = (b) => `${b.x},${b.y}`;
        const gen = new Set(lv.bolts.map(key));
        if (kept.some((b) => !gen.has(key(b)))) problems.push(`${profile} D${d}: kept a bolt that was never generated`);
        if (kept.map(key).join(';') !== again.map(key).join(';')) problems.push(`${profile} D${d}: not deterministic`);
        const buf = pool.take();
        const dist = bfsField(lv.map, lv.spawn.x, lv.spawn.y, buf);
        if (kept.some((b) => dist[b.y * lv.map.w + b.x] === UNREACHABLE)) problems.push(`${profile} D${d}: unreachable bolt kept`);
        pool.give(buf);
        const z = byDepth[beltDepth(d)];
        z.gen += lv.bolts.length; z.kept += kept.length; z.n++;
      }
    }
    // the runner actually applies it, and leaves it off when asked
    for (const d of [1, 5, 10, 47, 100]) {
      const on = new DistrictRunner({ profileId: 'bench', district: d, tier: 'medium' });
      const off = new DistrictRunner({ profileId: 'bench', district: d, tier: 'medium', thinBolts: false });
      if (on.game.bolts.length !== boltKeepCount(on.generatedBolts, d)) problems.push(`runner D${d} did not thin`);
      if (off.game.bolts.length !== off.generatedBolts) problems.push(`runner D${d} thinned with thinBolts: false`);
    }
    const curve = byDepth.map((z, k) => `${k + 1}: ${(z.kept / z.n).toFixed(1)}/${(z.gen / z.n).toFixed(1)}`).join(' · ');
    return problems.length ? ['FAIL', problems.slice(0, 5).join('; ')]
      : ['PASS', `300 districts. Mean bolts kept/generated by position in belt -- ${curve}`];
  },
}];
