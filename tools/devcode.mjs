// tools/devcode.mjs -- set the developer code for the 3D game's dev mode.
//
//   npm run devcode -- "your code"   use this code
//   npm run devcode                  invent a strong one and write it to DEV-MODE-CODE.txt
//
// Only a salted SHA-256 of the code goes into web3d/devhash.js, which is committed and
// published; the code itself never is. DEV-MODE-CODE.txt is git-ignored and stays on this
// machine. The live site takes a new code once devhash.js is committed and pushed with the
// usual 3D loop (changes entry, stamp3d, tests).
//
// Removed with the rest of dev mode by `npm run remove-devmode`.

import { createHash, randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = resolve(ROOT, 'web3d/devhash.js');
const CODE_FILE = resolve(ROOT, 'DEV-MODE-CODE.txt');

/** The same digest web3d/dev3d.js computes in the browser. */
export function digest(salt, code) {
  return createHash('sha256').update(`${salt}:${String(code).trim()}`, 'utf8').digest('hex');
}

function invent() {
  const alphabet = 'abcdefghjkmnpqrstuvwxyz23456789';   // no 0/o, 1/l/i
  const bytes = randomBytes(16);
  const chars = [...bytes].map((b) => alphabet[b % alphabet.length]);
  return [0, 4, 8, 12].map((i) => chars.slice(i, i + 4).join('')).join('-');
}

// Only when run as a script: criterion 3D-31 imports digest() from this file.
const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) main();

function main() {
const given = process.argv.slice(2).join(' ').trim();
const code = given || invent();
if (code.length < 6) {
  console.error('A developer code needs at least 6 characters.');
  process.exit(1);
}
const salt = randomBytes(8).toString('hex');
const hash = digest(salt, code);

writeFileSync(OUT, `// web3d/devhash.js -- GENERATED by \`npm run devcode\`. Do not edit by hand.
//
// A salted SHA-256 of the developer code (web3d/dev3d.js checks a typed code against it).
// The code itself is not in the repository.
export const DEV_SALT = '${salt}';
export const DEV_HASH = '${hash}';
`);

if (given) {
  console.log('Developer code set. Commit web3d/devhash.js (3D loop) for the live site to use it.');
} else {
  writeFileSync(CODE_FILE, `${code}\n`);
  console.log(`Developer code invented and written to ${CODE_FILE} (git-ignored; it is not printed here).`);
  console.log('Commit web3d/devhash.js (3D loop) for the live site to use it.');
}
}
